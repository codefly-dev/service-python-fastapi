// TestSettingsParseConnectEndpoint proves the setting reads at go-grpc's
// spelling, defaults to off, and is refused without a gRPC server to transcode
// onto.
func TestSettingsParseConnectEndpoint(t *testing.T) {
	var on Settings
	require.NoError(t, yaml.Unmarshal([]byte(`
grpc-server:
  enabled: true
connect-endpoint: true
`), &on))
	require.True(t, on.ConnectEndpoint)
	require.NoError(t, on.connectSettingError())

	var alone Settings
	require.NoError(t, yaml.Unmarshal([]byte(`connect-endpoint: true`), &alone))
	require.ErrorContains(t, alone.connectSettingError(), "grpc-server.enabled")

	var absent Settings
	require.NoError(t, yaml.Unmarshal([]byte(`python-version: "3.12"`), &absent))
	require.False(t, absent.ConnectEndpoint)
}

// TestSyncWritesTheConnectFace proves the face lands where the app imports it,
// byte for byte, replacing a hand edit.
func TestSyncWritesTheConnectFace(t *testing.T) {
	builder := NewBuilder(NewService())
	builder.Location = t.TempDir()
	builder.FastAPI.Settings.GRPCServer.Enabled = true
	builder.FastAPI.Settings.ConnectEndpoint = true

	target := filepath.Join(builder.Location, connectFacePath)
	require.NoError(t, os.MkdirAll(filepath.Dir(target), 0o755))
	require.NoError(t, os.WriteFile(target, []byte("# edited by hand\n"), 0o644))

	require.NoError(t, builder.writeConnectFace())
	written, err := os.ReadFile(target)
	require.NoError(t, err)
	require.Equal(t, connectFace, written)
	require.Contains(t, string(written), "Do not edit this file!")

	builder.FastAPI.Settings.GRPCServer.Enabled = false
	require.Error(t, builder.writeConnectFace())
}

// TestDeploymentRendersConnectPort proves the Connect container and Service
// ports appear only when the service opts in, declared as HTTP/1.1.
func TestDeploymentRendersConnectPort(t *testing.T) {
	enabled := agenttesting.AssertKustomizeTemplates(t, deploymentFS, deploymentTestParameters(t, Parameters{GRPCEnabled: true, GRPCPort: 9090, ConnectEnabled: true, ConnectPort: 8081}))
	svc, err := os.ReadFile(filepath.Join(enabled, "base", "service.yaml"))
	require.NoError(t, err)
	require.Contains(t, string(svc), "name: connect-port")
	require.Contains(t, string(svc), "appProtocol: http\n")
	require.Contains(t, string(svc), "port: 8081")
	deployment, err := os.ReadFile(filepath.Join(enabled, "base", "deployment.yaml"))
	require.NoError(t, err)
	require.Contains(t, string(deployment), "containerPort: 8081")

	disabled := agenttesting.AssertKustomizeTemplates(t, deploymentFS, deploymentTestParameters(t, Parameters{GRPCEnabled: true, GRPCPort: 9090}))
	svc, err = os.ReadFile(filepath.Join(disabled, "base", "service.yaml"))
	require.NoError(t, err)
	require.NotContains(t, string(svc), "connect-port")
}

// TestConnectFaceServesEveryProtocol runs the face's own suite
// (testdata/connect) against a real grpc.aio server: Connect unary and server
// streams in both codecs, gRPC-Web, gRPC relayed on the same port, metadata
// both ways, the service's interceptors on every protocol, deadlines and the
// HTTP refusals. The Python pins are the ones a service's lock resolves today.
func TestConnectFaceServesEveryProtocol(t *testing.T) {
	if _, err := exec.LookPath("uv"); err != nil {
		t.Skip("uv is not installed: the Connect face's Python suite cannot run")
	}
	cmd := exec.Command("uv", "run", "--no-project", "--python", "3.12",
		"--with", "grpcio==1.84.0", "--with", "protobuf==6.33.6", "--with", "h11==0.16.0",
		"--with", "httpx==0.28.1", "--with", "pytest==8.4.2", "--with", "pytest-asyncio==1.2.0",
		"pytest", "-q", "-p", "no:cacheprovider",
		"-o", "asyncio_mode=auto", "-o", "asyncio_default_fixture_loop_scope=function",
		filepath.Join("testdata", "connect"))
	cmd.Env = append(os.Environ(), "PYTHONPATH="+filepath.Join("templates", "connect"), "PYTHONDONTWRITEBYTECODE=1")
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s", out)
}

// TestBuilderLoadReadsTheAgentsSettings is the regression guard for a loaded
// (not created) service: the builder must see grpc-server and
// connect-endpoint, or Sync writes neither the gRPC stubs nor the Connect face
// and Deploy renders neither port.
func TestBuilderLoadReadsTheAgentsSettings(t *testing.T) {
	created, _ := createServiceForTest(t, map[string]*agentv0.Answer{
		HotReload:      confirmAnswer(false),
		PublicEndpoint: confirmAnswer(false),
		GRPCServer:     confirmAnswer(true),
	})
	ctx := context.Background()
	manifest := filepath.Join(created.Location, "service.codefly.yaml")
	content, err := os.ReadFile(manifest)
	require.NoError(t, err)
	var document map[string]any
	require.NoError(t, yaml.Unmarshal(content, &document))
	spec, _ := document["spec"].(map[string]any)
	require.Equal(t, true, spec["grpc-server"].(map[string]any)["enabled"])
	spec["connect-endpoint"] = true
	content, err = yaml.Marshal(document)
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(manifest, content, 0o644))

	identity, err := created.Identity.Proto()
	require.NoError(t, err)
	loaded := NewBuilder(NewService())
	resp, err := loaded.Load(ctx, &builderv0.LoadRequest{Identity: identity})
	require.NoError(t, err)
	require.NotEqual(t, builderv0.LoadStatus_ERROR, resp.GetState().GetState(), resp.GetState().GetMessage())
	require.True(t, loaded.FastAPI.Settings.GRPCServer.Enabled)
	require.True(t, loaded.FastAPI.Settings.ConnectEndpoint)
	require.Equal(t, filepath.Join(created.Location, "code"), loaded.Service.SourceLocation)
}
