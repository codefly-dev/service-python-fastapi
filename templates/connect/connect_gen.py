class CallError(Exception):
    """A call answered with a gRPC status other than OK, before or by the service."""

    def __init__(self, code: grpc.StatusCode, message: str, header=(), trailer=()):
        super().__init__(message)
        self.code, self.message = code, message
        self.header, self.trailer = tuple(header), tuple(trailer)

    @classmethod
    def of(cls, error: grpc.aio.AioRpcError) -> CallError:
        return cls(
            error.code(),
            error.details() or "",
            error.initial_metadata() or (),
            error.trailing_metadata() or (),
        )


class _Plain(Exception):
    """A request refused at the HTTP layer, before any protocol is spoken."""

    def __init__(self, status: int, reason: str, headers=()):
        super().__init__(reason)
        self.status, self.reason, self.headers = status, reason, list(headers)


class ConnectFace:
    """The listener ``serve`` starts; ``stop`` closes it and every open connection."""

    def __init__(self, server, channel, port: int):
        self._server, self._channel, self.port = server, channel, port
        self._connections: set[asyncio.Task] = set()

    async def stop(self, grace: float | None = 5.0) -> None:
        self._server.close()
        for task in list(self._connections):
            task.cancel()
        if self._connections:
            await asyncio.wait(self._connections, timeout=grace)
        await self._channel.close()


async def serve(
    port: int,
    grpc_port: int,
    *,
    host: str = "0.0.0.0",
    grpc_host: str = "127.0.0.1",
    max_message_bytes: int = DEFAULT_MAX_MESSAGE_BYTES,
    read_timeout: float = DEFAULT_READ_TIMEOUT_S,
    idle_timeout: float = DEFAULT_IDLE_TIMEOUT_S,
) -> ConnectFace:
    """Start the Connect face on ``host``:``port`` (0 for an ephemeral one) over the
    grpc.aio server listening on ``grpc_host``:``grpc_port``, and return it started.
    Call it on the loop that serves the gRPC server, once that server listens."""
    target = f"{grpc_host}:{grpc_port}"
    channel = grpc.aio.insecure_channel(
        target,
        options=[
            ("grpc.max_receive_message_length", max_message_bytes),
            ("grpc.max_send_message_length", max_message_bytes),
        ],
    )
    connection = _Connection(
        channel, (grpc_host, grpc_port), max_message_bytes, read_timeout, idle_timeout
    )
    face: ConnectFace

    async def accepted(reader, writer):
        task = asyncio.current_task()
        face._connections.add(task)
        try:
            await connection.serve(reader, writer)
        except asyncio.CancelledError:
            pass
        except Exception:  # one connection's failure never stops the listener
            _log.exception("connect face: connection failed")
        finally:
            face._connections.discard(task)
            writer.close()

    server = await asyncio.start_server(accepted, host, port)
    bound = server.sockets[0].getsockname()[1]
    face = ConnectFace(server, channel, bound)
    return face


async def start(grpc_port: int, **options) -> ConnectFace | None:
    """Start the face the agent's generated ``src/main.py`` starts: on
    ``CODEFLY_CONNECT_PORT`` over the gRPC server on ``grpc_port``, with ``serve``'s
    ``options``. Without that variable the service does not set ``connect-endpoint``:
    return None, starting nothing, and say why."""
    port = os.environ.get(PORT_ENV)
    if not port:
        _log.warning(
            "connect face: %s is unset, so connect-endpoint is off: not serving", PORT_ENV
        )
        return None
    return await serve(int(port), grpc_port, **options)


class _ProtocolError(Exception):
    """A client frame no HTTP/2 client may send: the relay closes the connection."""


class _Frames:
    """The HTTP/2 frames in one direction of a relayed connection, after the preface:
    ``on_frame(type, flags, stream, payload)`` for each. The payload is read for SETTINGS
    and GOAWAY only (at most ``_CONTROL_PAYLOAD`` bytes of it) and skipped otherwise."""

    def __init__(self, on_frame):
        self._on_frame = on_frame
        self._header = bytearray()
        self._frame = None  # (type, flags, stream) while its payload is read
        self._payload = bytearray()
        self._keep = 0  # payload bytes still to read
        self._skip = 0  # payload bytes still to skip

    def feed(self, data: bytes) -> None:
        at = 0
        while at < len(data):
            if self._keep:
                step = min(self._keep, len(data) - at)
                self._payload += data[at : at + step]
                self._keep -= step
                at += step
                if not self._keep:
                    self._emit()
                continue
            if self._skip:
                step = min(self._skip, len(data) - at)
                self._skip -= step
                at += step
                continue
            step = min(_FRAME.size - len(self._header), len(data) - at)
            self._header += data[at : at + step]
            at += step
            if len(self._header) == _FRAME.size:
                high, low, kind, flags, stream = _FRAME.unpack(self._header)
                self._header.clear()
                length = high << 16 | low
                self._frame = (kind, flags, stream & 0x7FFFFFFF)
                if kind in (_SETTINGS, _GOAWAY):
                    self._keep = min(length, _CONTROL_PAYLOAD)
                    self._skip = length - self._keep
                else:
                    self._skip = length
                if not self._keep:
                    self._emit()

    def _emit(self):
        payload = bytes(self._payload)
        self._payload.clear()
        self._on_frame(*self._frame, payload)


class _Connection:
    def __init__(self, channel, grpc_address, limit, read_timeout, idle_timeout):
        self.channel, self.grpc_address, self.limit = channel, grpc_address, limit
        self.read_timeout, self.idle_timeout = read_timeout, idle_timeout

    async def serve(self, reader, writer):
        head = b""
        async with asyncio.timeout(self.read_timeout):
            while len(head) < len(_PREFACE) and _PREFACE.startswith(head):
                chunk = await reader.read(len(_PREFACE) - len(head))
                if not chunk:
                    break
                head += chunk
        if head == _PREFACE:
            await self._relay(reader, writer, head)
        elif head:
            await self._http1(reader, writer, head)

    async def _relay(self, reader, writer, head):
        """gRPC over HTTP/2: the bytes go to the gRPC server as they came, until either
        side closes, or the connection has had no open call for ``idle_timeout``.

        The frame headers say which calls are open: a client HEADERS on a new stream (odd,
        above every stream before it) opens one, and the server's END_STREAM, either
        side's RST_STREAM, or the server's GOAWAY above the stream ends it. A client that
        opens an even stream, or more calls than the server allows at once
        (SETTINGS_MAX_CONCURRENT_STREAMS, ``DEFAULT_MAX_OPEN_CALLS`` when it advertises
        none), is closed: no HTTP/2 client does either."""
        upstream_reader, upstream_writer = await asyncio.open_connection(*self.grpc_address)
        upstream_writer.write(head)
        loop = asyncio.get_running_loop()
        last = loop.time()
        calls: set[int] = set()
        highest = 0
        max_calls = DEFAULT_MAX_OPEN_CALLS

        def from_client(kind, flags, stream, payload):
            nonlocal highest
            if kind == _HEADERS:
                if stream % 2 == 0:
                    raise _ProtocolError(f"HEADERS on stream {stream}, which a server opens")
                if stream <= highest:
                    # Trailers on a call, or a stream the server refuses as closed:
                    # never a new call.
                    return
                highest = stream
                if len(calls) >= max_calls:
                    raise _ProtocolError(f"more than {max_calls} calls open at once")
                calls.add(stream)
            elif kind == _RST_STREAM:
                calls.discard(stream)

        def from_server(kind, flags, stream, payload):
            nonlocal max_calls
            if kind == _RST_STREAM or (kind in (_DATA, _HEADERS) and flags & _END_STREAM_FLAG):
                calls.discard(stream)
            elif kind == _SETTINGS and not flags & _ACK_FLAG:
                for at in range(0, len(payload) - 5, 6):
                    key, value = struct.unpack_from(">HI", payload, at)
                    if key == _MAX_CONCURRENT_STREAMS:
                        max_calls = value
            elif kind == _GOAWAY and len(payload) >= 4:
                # Streams above the last one the server processes are never answered.
                last_stream = struct.unpack_from(">I", payload)[0] & 0x7FFFFFFF
                calls.difference_update({call for call in calls if call > last_stream})

        async def pump(source, sink, frames):
            nonlocal last
            try:
                while chunk := await source.read(65536):
                    last = loop.time()
                    frames.feed(chunk)
                    sink.write(chunk)
                    await sink.drain()
            except (ConnectionError, OSError):
                pass
            except _ProtocolError as refusal:
                _log.info("connect face: closing a gRPC connection: %s", refusal)

        async def idle():
            # The clock runs from the last byte either way, and only ends the connection
            # while no call is open: a handler computing an answer sends nothing.
            while True:
                remaining = last + self.idle_timeout - loop.time()
                if remaining <= 0 and not calls:
                    return
                await asyncio.sleep(remaining if remaining > 0 else self.idle_timeout)

        tasks = (
            asyncio.ensure_future(pump(reader, upstream_writer, _Frames(from_client))),
            asyncio.ensure_future(pump(upstream_reader, writer, _Frames(from_server))),
            asyncio.ensure_future(idle()),
        )
        try:
            # Either side closing ends the relay: an HTTP/2 connection is not half-closed,
            # and a call still recorded open cannot be answered once its server has gone.
            await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
        finally:
            for task in tasks:
                task.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)
            upstream_writer.close()

    async def _read(self, reader, timeout):
        async with asyncio.timeout(timeout):
            return await reader.read(65536)

    async def _event(self, conn, reader, timeout):
        while True:
            event = conn.next_event()
            if event is not h11.NEED_DATA:
                return event
            conn.receive_data(await self._read(reader, timeout))

    async def _http1(self, reader, writer, head):
        conn = h11.Connection(h11.SERVER)
        conn.receive_data(head)
        timeout = self.read_timeout
        while True:
            try:
                event = await self._event(conn, reader, timeout)
            except (TimeoutError, h11.RemoteProtocolError, ConnectionError):
                return
            if not isinstance(event, h11.Request):
                return
            exchange = _Exchange(conn, writer)
            try:
                body = await self._body(conn, reader, event)
                await self._dispatch(exchange, event, body)
            except _Plain as refusal:
                await exchange.plain(refusal)
                return  # the body may be unread: the connection cannot be reused
            except (TimeoutError, h11.RemoteProtocolError):
                return
            if conn.our_state is not h11.DONE or conn.their_state is not h11.DONE:
                return
            conn.start_next_cycle()
            timeout = self.idle_timeout

    async def _body(self, conn, reader, request):
        bound = self.limit + _ENVELOPE.size
        declared = next((v for k, v in request.headers if k == b"content-length"), None)
        if declared is not None and int(declared) > bound:
            raise _Plain(413, f"content length ({int(declared)}) exceeds the message bound")
        body = bytearray()
        while True:
            event = await self._event(conn, reader, self.read_timeout)
            if isinstance(event, h11.Data):
                body += event.data
                if len(body) > bound:
                    raise _Plain(413, "request body exceeds the message bound")
            elif isinstance(event, h11.EndOfMessage):
                return bytes(body)
            else:
                raise h11.RemoteProtocolError("connection closed inside a request body")

    async def _dispatch(self, exchange, request, body):
        if request.method != b"POST":
            raise _Plain(405, "only POST is served", [(b"allow", b"POST")])
        path = request.target.split(b"?", 1)[0].decode("latin-1")
        method = _method(path)
        if method is None:
            raise _Plain(404, f"no procedure {path}")
        headers = {}
        for name, value in request.headers:
            headers.setdefault(name.decode("latin-1"), value.decode("latin-1"))
        content_type = headers.get("content-type", "")
        media = content_type.split(";", 1)[0].strip().lower()
        if media.startswith("application/grpc-web"):
            protocol = _GRPCWeb(media)
        elif media.startswith("application/connect+"):
            protocol = _ConnectStream(media)
        elif media in ("application/proto", "application/json"):
            protocol = _ConnectUnary(media)
        else:
            raise _Plain(
                415,
                f"unsupported content type {content_type!r}",
                [(b"accept-post", b"application/proto, application/json")],
            )
        codec = protocol.codec
        if codec is None:
            raise _Plain(415, f"unsupported codec in {content_type!r}")
        call = _Call(self.channel, path, method, codec, request.headers, headers, self.limit)
        await protocol.answer(exchange, call, body, headers)


def _method(path):
    service, _, name = path.lstrip("/").partition("/")
    if not service or not name or "/" in name:
        return None
    try:
        found = descriptor_pool.Default().FindServiceByName(service)
    except KeyError:
        return None
    return found.methods_by_name.get(name)


class _Codec:
    def __init__(self, name):
        self.name = name

    def request(self, cls, data: bytes) -> bytes:
        if self.name == "proto":
            return data
        try:
            # Unknown fields are dropped, as connect-go's JSON codec does: a client built
            # from a newer contract still reaches a service on the older one.
            message = json_format.Parse(data or b"{}", cls(), ignore_unknown_fields=True)
            return message.SerializeToString()
        except (json_format.ParseError, UnicodeDecodeError, ValueError) as exc:
            raise CallError(grpc.StatusCode.INVALID_ARGUMENT, f"unmarshal JSON: {exc}") from exc

    def response(self, cls, data: bytes) -> bytes:
        if self.name == "proto":
            return data
        document = json_format.MessageToDict(cls.FromString(data))
        return json.dumps(document, separators=(",", ":")).encode()


def _codec(name):
    return _Codec(name) if name in ("proto", "json") else None


class _Call:
    """One call dispatched through the gRPC server: request bytes in the protocol's
    codec, answers out in it."""

    def __init__(self, channel, path, method, codec, raw_headers, headers, limit):
        self.channel, self.path, self.method, self.codec = channel, path, method, codec
        self.limit = limit
        self.input = message_factory.GetMessageClass(method.input_type)
        self.output = message_factory.GetMessageClass(method.output_type)
        self.metadata = _metadata(raw_headers)
        self.timeout = _timeout(headers)

    def refuse_streams(self):
        if self.method.client_streaming:
            raise CallError(
                grpc.StatusCode.UNIMPLEMENTED,
                f"{self.path} streams its requests: it is served on the gRPC protocol only",
            )

    def decompress(self, data: bytes, encoding: str | None) -> bytes:
        if encoding in (None, "", "identity"):
            payload = data
        elif encoding == "gzip":
            inflater = zlib.decompressobj(16 + zlib.MAX_WBITS)
            try:
                payload = inflater.decompress(data, self.limit + 1)
            except zlib.error as exc:
                raise CallError(grpc.StatusCode.INVALID_ARGUMENT, f"gzip: {exc}") from exc
            if inflater.unconsumed_tail:
                payload += b"\0"  # still more than the bound
        else:
            raise CallError(grpc.StatusCode.UNIMPLEMENTED, f"unknown compression {encoding!r}")
        if len(payload) > self.limit:
            raise CallError(
                grpc.StatusCode.RESOURCE_EXHAUSTED,
                f"message exceeds the message bound ({self.limit})",
            )
        return payload

    async def unary(self, message: bytes):
        """The answer and the header and trailer metadata of a unary call."""
        request = self.codec.request(self.input, message)
        call = self.channel.unary_unary(self.path)(
            request, metadata=self.metadata, timeout=self.timeout
        )
        try:
            answer = await call
            return (
                self.codec.response(self.output, answer),
                tuple(await call.initial_metadata() or ()),
                tuple(await call.trailing_metadata() or ()),
            )
        except grpc.aio.AioRpcError as exc:
            raise CallError.of(exc) from None

    def stream(self, message: bytes):
        request = self.codec.request(self.input, message)
        return self.channel.unary_stream(self.path)(
            request, metadata=self.metadata, timeout=self.timeout
        )


class _Exchange:
    """The response side of one HTTP/1.1 exchange."""

    def __init__(self, conn, writer):
        self.conn, self.writer = conn, writer

    async def send(self, *events):
        for event in events:
            data = self.conn.send(event)
            if data:
                self.writer.write(data)
        await self.writer.drain()

    async def whole(self, status, headers, body: bytes):
        headers = [*headers, (b"content-length", str(len(body)).encode())]
        await self.send(
            h11.Response(status_code=status, headers=headers),
            h11.Data(data=body),
            h11.EndOfMessage(),
        )

    async def plain(self, refusal: _Plain):
        if self.conn.our_state is not h11.SEND_RESPONSE:
            return
        headers = [(b"content-type", b"text/plain; charset=utf-8"), (b"connection", b"close")]
        await self.whole(refusal.status, headers + refusal.headers, refusal.reason.encode())


class _ConnectUnary:
    def __init__(self, media):
        self.media = media
        self.codec = _codec(media.removeprefix("application/"))

    async def answer(self, exchange, call, body, headers):
        response_type = [(b"content-type", self.media.encode())]
        try:
            call.refuse_streams()
            if call.method.server_streaming:
                raise CallError(
                    grpc.StatusCode.UNIMPLEMENTED,
                    f"{call.path} streams its answers: call it with application/connect+",
                )
            message = call.decompress(body, headers.get("content-encoding"))
            answer, header, trailer = await call.unary(message)
        except CallError as error:
            status = _CODES.get(error.code, ("unknown", 500))[1]
            out = [(b"content-type", b"application/json")]
            out += _headers(error.header) + _headers(_without_details(error.trailer), b"trailer-")
            await exchange.whole(status, out, json.dumps(_error(error)).encode())
            return
        out = response_type + _headers(header) + _headers(trailer, b"trailer-")
        await exchange.whole(200, out, answer)


class _ConnectStream:
    def __init__(self, media):
        self.media = media
        self.codec = _codec(media.removeprefix("application/connect+"))

    async def answer(self, exchange, call, body, headers):
        stream, header = await _open(call, body, headers.get("connect-content-encoding"))
        await exchange.send(
            h11.Response(
                status_code=200,
                headers=[(b"content-type", self.media.encode()), *_headers(header)],
            )
        )
        outcome = await _relay(exchange, call, stream)
        if isinstance(outcome, CallError):
            end = _end_stream(outcome)
        else:
            end = {"metadata": _metadata_document(outcome)} if outcome else {}
        frame = json.dumps(end, separators=(",", ":")).encode()
        await exchange.send(
            h11.Data(data=_ENVELOPE.pack(_END_STREAM, len(frame)) + frame), h11.EndOfMessage()
        )


class _GRPCWeb:
    def __init__(self, media):
        self.media = media
        subtype = media.removeprefix("application/grpc-web")
        self.codec = _codec(subtype.removeprefix("+") or "proto")

    async def answer(self, exchange, call, body, headers):
        stream, header = await _open(call, body, headers.get("grpc-encoding"))
        await exchange.send(
            h11.Response(
                status_code=200,
                headers=[(b"content-type", self.media.encode()), *_headers(header)],
            )
        )
        outcome = await _relay(exchange, call, stream)
        if isinstance(outcome, CallError):
            code, message, trailer = outcome.code, outcome.message, outcome.trailer
        else:
            code, message, trailer = grpc.StatusCode.OK, "", outcome
        lines = [f"grpc-status: {code.value[0]}"]
        if message:
            lines.append(f"grpc-message: {_percent(message)}")
        lines += [f"{k.decode()}: {v.decode('latin-1')}" for k, v in _headers(trailer)]
        if code is not grpc.StatusCode.OK and (details := _status_details(trailer)):
            lines.append(f"{_STATUS_DETAILS}: {details.decode()}")
        block = ("\r\n".join(lines) + "\r\n").encode("latin-1")
        await exchange.send(
            h11.Data(data=_ENVELOPE.pack(_TRAILERS, len(block)) + block), h11.EndOfMessage()
        )


class _Answered:
    """A unary answer, relayed as a stream of one."""

    def __init__(self, answer, trailer):
        self.answer, self.trailer = answer, trailer


class _Refused:
    """A call refused before its first answer."""

    def __init__(self, error: CallError):
        self.error = error


async def _open(call, body, encoding):
    """Start the call an enveloped request asks for; return what to relay and the header
    metadata to answer with. A refusal is relayed too: these protocols always answer 200
    and carry the status at the end of the stream."""
    try:
        call.refuse_streams()
        payload, compressed = _one_message(body)
        message = call.decompress(payload, encoding if compressed else None)
        if call.method.server_streaming:
            stream = call.stream(message)
            return stream, tuple(await stream.initial_metadata() or ())
        answer, header, trailer = await call.unary(message)
        return _Answered(answer, trailer), header
    except CallError as error:
        return _Refused(error), error.header


async def _relay(exchange, call, stream):
    """Write every answer enveloped; return the trailer metadata, or the CallError the
    call ended with."""
    if isinstance(stream, _Refused):
        return stream.error
    if isinstance(stream, _Answered):
        frame = _ENVELOPE.pack(0, len(stream.answer)) + stream.answer
        await exchange.send(h11.Data(data=frame))
        return stream.trailer
    try:
        async for answer in stream:
            data = call.codec.response(call.output, answer)
            await exchange.send(h11.Data(data=_ENVELOPE.pack(0, len(data)) + data))
        return tuple(await stream.trailing_metadata() or ())
    except grpc.aio.AioRpcError as exc:
        return CallError.of(exc)
    finally:
        stream.cancel()


def _end_stream(error: CallError) -> dict:
    end: dict = {"error": _error(error)}
    trailer = _without_details(error.trailer)
    if trailer:
        end["metadata"] = _metadata_document(trailer)
    return end


def _one_message(body: bytes):
    if len(body) < _ENVELOPE.size:
        raise CallError(grpc.StatusCode.INVALID_ARGUMENT, "truncated message envelope")
    flags, size = _ENVELOPE.unpack_from(body)
    payload = body[_ENVELOPE.size :]
    if len(payload) != size:
        raise CallError(grpc.StatusCode.INVALID_ARGUMENT, "exactly one request message expected")
    return payload, bool(flags & _COMPRESSED)


def _metadata(raw_headers):
    metadata = []
    for raw_name, raw_value in raw_headers:
        name = raw_name.decode("latin-1").lower()
        if name in _TRANSPORT or name.startswith(_TRANSPORT_PREFIXES):
            continue
        value = raw_value.decode("latin-1")
        if name.endswith("-bin"):
            try:
                metadata.append((name, base64.b64decode(value + "=" * (-len(value) % 4))))
            except ValueError:
                raise _Plain(400, f"header {name} is not base64") from None
        else:
            metadata.append((name, value))
    return tuple(metadata)


def _timeout(headers):
    if (millis := headers.get("connect-timeout-ms")) is not None:
        if not millis.isdigit() or len(millis) > 10:
            raise _Plain(400, "connect-timeout-ms is not a duration in milliseconds")
        return int(millis) / 1000
    if (grpc_timeout := headers.get("grpc-timeout")) is not None:
        match = _GRPC_TIMEOUT.match(grpc_timeout)
        if match is None:
            raise _Plain(400, "grpc-timeout is not a gRPC duration")
        return int(match.group(1)) * _GRPC_UNITS[match.group(2)]
    return None


def _header_value(key: str, value) -> bytes:
    if key.endswith("-bin") or isinstance(value, bytes):
        raw = value if isinstance(value, bytes) else value.encode()
        return base64.b64encode(raw).rstrip(b"=")
    return value.encode("latin-1", "replace")


def _headers(metadata: Iterable, prefix: bytes = b""):
    out = []
    for key, value in metadata:
        if key.startswith(("grpc-", ":")) or key == "content-type":
            continue
        out.append((prefix + key.encode("latin-1"), _header_value(key, value)))
    return out


def _metadata_document(metadata) -> dict:
    document: dict[str, list[str]] = {}
    for key, value in metadata:
        if key.startswith(("grpc-", ":")):
            continue
        document.setdefault(key, []).append(_header_value(key, value).decode("latin-1"))
    return document


def _without_details(trailer):
    return tuple((k, v) for k, v in trailer if k != _STATUS_DETAILS)


def _error(error: CallError) -> dict:
    document: dict = {"code": _CODES.get(error.code, ("unknown", 500))[0]}
    if error.message:
        document["message"] = error.message
    details = _details(error.trailer)
    if details:
        document["details"] = details
    return document


def _status_details(trailer) -> bytes | None:
    """The google.rpc.Status a service attached, base64 as a header carries it."""
    raw = next((v for k, v in trailer if k == _STATUS_DETAILS), None)
    return base64.b64encode(raw).rstrip(b"=") if isinstance(raw, bytes) else None


def _details(trailer):
    """The google.rpc.Status details a service attached, as Connect's error details."""
    raw = next((v for k, v in trailer if k == _STATUS_DETAILS), None)
    if not isinstance(raw, bytes):
        return []
    details, at = [], 0
    try:
        while at < len(raw):
            key, at = _varint(raw, at)
            field, wire = key >> 3, key & 7
            if wire == 0:
                _, at = _varint(raw, at)
            elif wire == 2:
                size, at = _varint(raw, at)
                chunk, at = raw[at : at + size], at + size
                if field == 3:
                    detail = any_pb2.Any.FromString(chunk)
                    details.append(
                        {
                            "type": detail.type_url.rsplit("/", 1)[-1],
                            "value": base64.b64encode(detail.value).rstrip(b"=").decode(),
                        }
                    )
            elif wire == 1:
                at += 8
            elif wire == 5:
                at += 4
            else:
                break
    except (IndexError, ValueError):
        _log.warning("connect face: unreadable %s trailer", _STATUS_DETAILS)
    return details


def _varint(data: bytes, at: int):
    value = shift = 0
    while True:
        byte = data[at]
        at += 1
        value |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return value, at
        shift += 7


def _percent(message: str) -> str:
    # gRPC's grpc-message encoding: printable ASCII but "%" as is, the rest percent-encoded.
    return quote(message, safe="".join(chr(c) for c in range(0x20, 0x7F) if c != 0x25))
